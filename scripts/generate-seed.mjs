// Writes migrations/0002_seed_content.sql from scripts/seed-data.mjs and the previous
// site's translations. Run once with `node scripts/generate-seed.mjs` and commit the output.
// It also writes scripts/seed-media.json, the list of photos scripts/upload-seed-media.mjs
// copies into R2 so the seeded tours have pictures.
import { buildSync } from 'esbuild'
import { createHash } from 'node:crypto'
import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, extname } from 'node:path'
import { content, destinations, settings, tours } from './seed-data.mjs'

const built = buildSync({ entryPoints: ['src/i18n/translations.ts'], bundle: true, format: 'esm', write: false })
const { translations } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`)

// Keys of the previous site's copy, per tour.
const legacy = {
  adventure: ['adventureTours', 'activityAdventureCardDesc', 'adventureDesc'],
  'ile-aux-cerfs': ['ileAuxCerfsTours', 'activityIleAuxCerfsCardDesc', 'ileAuxCerfsDesc'],
  hiking: ['hiking', 'activityHikingCardDesc', 'hikingDesc'],
  quad: ['quadBikes', 'activityQuadCardDesc', 'quadDesc'],
  catamaran: ['catamaranSpeedBoat', 'activityCatamaranCardDesc', 'catamaranDesc'],
  'big-game-fishing': ['bigGameFishing', 'activityBigGameFishingCardDesc', 'bigGameFishingDesc'],
}
const langs = ['en', 'fr', 'ru']
const NOW = Date.parse('2026-10-28T00:00:00Z')

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`)
const json = (v) => q(JSON.stringify(v))
// Width and height from a JPEG's frame header, so the site can reserve space for each photo.
function jpegSize(file) {
  const buf = readFileSync(file)
  let i = 2
  while (i < buf.length) {
    const marker = buf[i + 1]
    const length = buf.readUInt16BE(i + 2)
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) return { width: buf.readUInt16BE(i + 7), height: buf.readUInt16BE(i + 5) }
    i += 2 + length
  }
  return { width: null, height: null }
}
const size = (file) => { const { width, height } = jpegSize(file); return `${width}, ${height}` }
const mimeOf = (file) => ({ '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' })[extname(file).toLowerCase()]

const lines = ['-- Generated by scripts/generate-seed.mjs. Starting content; admins edit it from /admin.', '']
const media = []

tours.forEach((tour, index) => {
  const id = index + 1
  const fixed = Boolean(tour.price)
  lines.push(
    `INSERT INTO tours (id, slug, category, status, sort_order, price_mode, price_adult_eur, price_child_eur, start_time, end_time, created_at, updated_at) VALUES (${[
      id, q(tour.slug), q(tour.category), q('published'), index * 10, q(fixed ? 'fixed' : 'on_request'),
      fixed ? tour.price.adult : 'NULL', fixed ? tour.price.child : 'NULL', q(tour.start ?? null), q(tour.end ?? null), NOW, NOW,
    ].join(', ')});`,
  )

  for (const lang of langs) {
    let text = tour.text?.[lang] ?? {}
    if (tour.from) {
      const [name, summary, description] = legacy[tour.from]
      text = { name: translations[lang][name], summary: translations[lang][summary], description: translations[lang][description] }
    }
    if (!text.name) continue
    lines.push(
      `INSERT INTO tour_translations (tour_id, lang, name, summary, description, stops, included, extras) VALUES (${[
        id, q(lang), q(text.name), q(text.summary ?? ''), q(text.description ?? ''),
        json(text.stops ?? []), json(text.included ?? []), json(text.extras ?? []),
      ].join(', ')});`,
    )
  }

  tour.images.forEach((path, imageIndex) => {
    const file = `public${path}`
    const mediaId = createHash('sha256').update(path).digest('hex').slice(0, 24)
    const key = `seed/${mediaId}${extname(path).toLowerCase()}`
    media.push({ file, key })
    const alt = tour.text?.en?.name ?? translations.en[legacy[tour.from][0]]
    lines.push(
      `INSERT INTO media (id, r2_key, mime, bytes, width, height, alt_en, created_at) VALUES (${q(mediaId)}, ${q(key)}, ${q(mimeOf(path))}, ${statSync(file).size}, ${size(file)}, ${q(alt)}, ${NOW});`,
      `INSERT INTO tour_media (tour_id, media_id, sort_order) VALUES (${id}, ${q(mediaId)}, ${imageIndex});`,
    )
    if (imageIndex === 0) lines.push(`UPDATE tours SET cover_media_id = ${q(mediaId)} WHERE id = ${id};`)
  })
  lines.push('')
})

// The previous site's static gallery becomes the first gallery items.
const galleryList = readFileSync('src/lib/static-gallery.ts', 'utf8').match(/'\/[^']+'/g).map((s) => s.slice(1, -1))
galleryList.forEach((path, index) => {
  const file = `public${path}`
  const mediaId = createHash('sha256').update(path).digest('hex').slice(0, 24)
  const key = `seed/${mediaId}${extname(path).toLowerCase()}`
  media.push({ file, key })
  lines.push(
    `INSERT INTO media (id, r2_key, mime, bytes, width, height, created_at) VALUES (${q(mediaId)}, ${q(key)}, ${q(mimeOf(path))}, ${statSync(file).size}, ${size(file)}, ${NOW});`,
    `INSERT INTO gallery_items (media_id, sort_order, created_at) VALUES (${q(mediaId)}, ${index * 10}, ${NOW});`,
  )
})
lines.push('')

destinations.forEach(([slug, name], index) => {
  lines.push(`INSERT INTO transfer_destinations (slug, name_en, sort_order) VALUES (${q(slug)}, ${q(name)}, ${index * 10});`)
})
lines.push('')

for (const [key, perLang] of Object.entries(content)) {
  for (const lang of langs) {
    lines.push(`INSERT INTO content_blocks (key, lang, value, updated_at) VALUES (${q(key)}, ${q(lang)}, ${json(perLang[lang])}, ${NOW});`)
  }
}
for (const lang of langs) {
  const about = { title: translations[lang].aboutTitle, paragraphs: [translations[lang].aboutText1, translations[lang].aboutText2] }
  lines.push(`INSERT INTO content_blocks (key, lang, value, updated_at) VALUES ('about', ${q(lang)}, ${json(about)}, ${NOW});`)
}
lines.push('')

for (const [key, value] of Object.entries(settings)) {
  lines.push(`INSERT INTO settings (key, value, updated_at) VALUES (${q(key)}, ${json(value)}, ${NOW});`)
}

writeFileSync('migrations/0002_seed_content.sql', `${lines.join('\n')}\n`)
writeFileSync('scripts/seed-media.json', `${JSON.stringify(media, null, 2)}\n`)
console.log(`Wrote ${tours.length} tours, ${media.length} photos, ${destinations.length} destinations.`)
console.log(media.map((m) => `  ${basename(m.file)} -> ${m.key}`).join('\n'))
